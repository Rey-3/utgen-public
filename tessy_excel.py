def writeGeneralSheet(ws, project_name, module_name, func_name, export_date=None):
    """Write the generated Test Object metadata to the TESSY General sheet.

    ``project_name`` is the raw project name from ``config.yaml``.  TESSY
    projects generated by UTGen use the ``tessy_`` prefix.  ``module_name``
    may be a full source path for compatibility with callers; only its
    basename is written to the workbook.
    """
    if export_date is None:
        export_date = date.today().isoformat()
    elif isinstance(export_date, date):
        export_date = export_date.isoformat()

    ws.cell(row=9, column=2).value = 'tessy_' + str(project_name)
    ws.cell(row=10, column=2).value = os.path.basename(os.fspath(module_name))
    ws.cell(row=11, column=2).value = func_name
    ws.cell(row=13, column=2).value = export_date


def value_sheet_names(sheetnames):
    """Return Values pages in numeric order, regardless of workbook tab order."""
    pages = []
    for name in sheetnames:
        match = re.fullmatch(r"Values(?: ([1-9][0-9]*))?", name)
        if match:
            pages.append((int(match.group(1) or 0), name))
    return [name for _, name in sorted(pages)]


def write_testlist_cells(workbook, rows, stubs, columns):
    """Write the shared TESSY Properties/Values/Stubs cell layout.

    ``rows`` contain ``id``, ``description``, ``input`` and ``output`` maps;
    ``columns`` contain ``(name, channel)`` pairs.  Keeping this helper at
    the physical-cell boundary lets old XML callers and JSON projection use
    the same layout without passing XML ranges around.
    """
    properties = workbook["Properties"]
    values = workbook["Values"]
    stubs_sheet = workbook["Stubs"]
    for name in value_sheet_names(workbook.sheetnames):
        if name != "Values":
            workbook.remove(workbook[name])
    # Only the main Values page carries testcase labels; numbered pages start at A.
    page_width = 98 if len(columns) + 1 > 16384 else 16383
    if page_width == 98:
        workbook.move_sheet(values, offset=len(workbook.worksheets) - 1 - workbook.index(values))
    for row in range(5, properties.max_row + 1):
        for column in range(1, max(properties.max_column, 8) + 1):
            properties.cell(row, column).value = None
    for row in range(1, values.max_row + 1):
        for column in range(1, values.max_column + 1):
            values.cell(row, column).value = None
    if values.max_column > page_width + 1:
        values.delete_cols(page_width + 2, values.max_column - page_width - 1)
    for row in range(5, stubs_sheet.max_row + 1):
        for column in range(1, max(stubs_sheet.max_column, 4) + 1):
            stubs_sheet.cell(row, column).value = None

    for index, row in enumerate(rows, 1):
        properties.cell(index + 4, 1).value = str(index)
        properties.cell(index + 4, 2).value = "0"
        description_cell = properties.cell(index + 4, 5)
        description_cell.value = (
            f"Test Case ID: {row['id']}\nDescription: {row['description']}"
        )
        alignment = copy(description_cell.alignment)
        alignment.wrap_text = True
        description_cell.alignment = alignment
    for page, start in enumerate(range(0, max(1, len(columns)), page_width)):
        target = values if page == 0 else workbook.create_sheet(f"Values {page}")
        first_column = 2 if page == 0 else 1
        page_columns = columns[start:start + page_width]
        for column_index, column in enumerate(page_columns, first_column):
            name, channel = column[:2]
            token = column[2] if len(column) > 2 else ("i" if channel == "input" else "o")
            target.cell(1, column_index).value = name
            target.cell(2, column_index).value = token
        for index, row in enumerate(rows, 1):
            if page == 0:
                target.cell(index + 2, 1).value = f"tc{index}.1"
            for column_index, column in enumerate(page_columns, first_column):
                name, channel = column[:2]
                source = row["input"] if channel == "input" else row["output"]
                target.cell(index + 2, column_index).value = source[name]
    for index, stub in enumerate(stubs, 5):
        stubs_sheet.cell(index, 1).value = "0"
        stubs_sheet.cell(index, 2).value = "0"
        stubs_sheet.cell(index, 3).value = stub["name"]
        stubs_sheet.cell(index, 4).value = stub["body"]


def save_test_workbook(workbook, path):
    """Use real XLS only for pages split above the XLSX column limit."""
    oversized = len(value_sheet_names(workbook.sheetnames)) > 1
    path = Path(path).with_suffix(".xls" if oversized else ".xlsx")
    if not oversized:
        with path.open("wb") as stream:
            workbook.save(stream)
        return path
    import xlwt
    from openpyxl.utils.cell import column_index_from_string

    output = xlwt.Workbook()
    styles = {}
    for sheet in workbook:
        if sheet.max_row > 65536 or sheet.max_column > 256:
            raise ValueError(f"XLS worksheet limit exceeded in {sheet.title}: 65536 rows / 256 columns")
        target = output.add_sheet(sheet.title, cell_overwrite_ok=True)
        # ponytail: preserve basic text formatting; map palettes/borders if XLS styling needs them.
        for (row, column), cell in sheet._cells.items():
            if cell.style_id not in styles:
                style = xlwt.XFStyle()
                style.num_format_str = cell.number_format
                style.font.name = cell.font.name or "Arial"
                style.font.height = int((cell.font.sz or 11) * 20)
                style.font.bold = bool(cell.font.bold)
                style.font.italic = bool(cell.font.italic)
                style.alignment.wrap = bool(cell.alignment.wrap_text)
                style.alignment.horz = {"left": 1, "center": 2, "right": 3}.get(cell.alignment.horizontal, 0)
                style.alignment.vert = {"top": 0, "center": 1, "bottom": 2}.get(cell.alignment.vertical, 2)
                styles[cell.style_id] = style
            value = xlwt.Formula(cell.value[1:]) if cell.data_type == "f" else cell.value
            target.write(row - 1, column - 1, value, styles[cell.style_id])
        for name, dimension in sheet.column_dimensions.items():
            first = dimension.min or column_index_from_string(name)
            last = dimension.max or first
            for column in range(first, min(last, 256) + 1):
                target.col(column - 1).width = min(65535, int(dimension.width * 256))
        for row, dimension in sheet.row_dimensions.items():
            if row <= 65536 and dimension.height is not None:
                target.row(row - 1).height = int(dimension.height * 20)
        for merged in sheet.merged_cells.ranges:
            target.merge(merged.min_row - 1, merged.max_row - 1, merged.min_col - 1, merged.max_col - 1)
    with path.open("wb") as stream:
        output.save(stream)
    return path


def updateTestlistToExcel(func , templateFile , saveFileName , testList , testMethodlist , stubList , arg_name , arg_direction , arg_format,
                          project_name=None, module_name=None, export_date=None):
    wb = load_workbook(templateFile)
    if project_name is not None or module_name is not None or export_date is not None:
        if project_name is None or module_name is None:
            raise ValueError("project_name and module_name are required to write General metadata")
        writeGeneralSheet(wb.worksheets[0], project_name, module_name, func, export_date)
    columns = []
    typed_vars = set()
    for name, direction, fmt in zip(arg_name, arg_direction, arg_format):
        channel = "input" if direction in {"in", "inout"} else "output"
        base = name.split('.')[0].split('[')[0]
        columns.append((name, channel, convertDirectionToTessyFormat(direction, name, fmt, name.startswith("tessy_") and base not in typed_vars)))
        typed_vars.add(base)
    rows = []
    for index, values in enumerate(testList, 1):
        description = f"测试{func}() 的正向测试"
        rows.append({
            "id": f"UT_TBD_{index:03d}",
            "description": description,
            "input": {name: str(value) for name, value, direction in zip(arg_name, values, arg_direction) if direction in {"in", "inout"}},
            "output": {name: str(value) for name, value, direction in zip(arg_name, values, arg_direction) if direction in {"out", "inout"}},
        })
    value_vars = {name.split('.')[0] for name in arg_name}
    stubs = []
    for name, ret_type, ret_name, _ in stubList:
        has_return = ret_type not in ("void", "static void")
        provides_value = ret_name in value_vars
        body = ""
        if has_return and provides_value:
            body = f"extern {ret_type} {ret_name};\rreturn {ret_name};\r"
        elif has_return:
            body = f"{ret_type} temp = {{0}};\rreturn temp;\r"
        stubs.append({"name": name, "body": body})
    write_testlist_cells(wb, rows, stubs, columns)
    save_test_workbook(wb, saveFileName)

def convertDirectionToTessyFormat(direction , name='' , fmt='', show_type=True):
    newDir = 'i' if direction == "in" else 'o'
    if show_type:
        newDir += '(' + fmt + ')'
    return newDir
