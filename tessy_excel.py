from datetime import date
import os

from openpyxl import load_workbook

### need to install https://openpyxl.readthedocs.io/en/stable/
def writeGeneralSheet(ws, project_name, module_name, func_name, export_date=None):
    """Write the generated Test Object metadata to the TESSY General sheet.

    ``project_name`` is the raw project name from ``config.yaml``.  TESSY
    projects generated by UTGen use the ``tessy_`` prefix.  ``module_name``
    may be a full source path for compatibility with callers; only its
    basename is written to the workbook.
    """
    if export_date is None:
        export_date = date.today().isoformat()
    elif isinstance(export_date, date):
        export_date = export_date.isoformat()

    ws.cell(row=9, column=2).value = 'tessy_' + str(project_name)
    ws.cell(row=10, column=2).value = os.path.basename(os.fspath(module_name))
    ws.cell(row=11, column=2).value = func_name
    ws.cell(row=13, column=2).value = export_date


def write_testlist_cells(workbook, rows, stubs, columns):
    """Write the shared TESSY Properties/Values/Stubs cell layout.

    ``rows`` contain ``id``, ``description``, ``input`` and ``output`` maps;
    ``columns`` contain ``(name, channel)`` pairs.  Keeping this helper at
    the physical-cell boundary lets old XML callers and JSON projection use
    the same layout without passing XML ranges around.
    """
    properties = workbook["Properties"]
    values = workbook["Values"]
    stubs_sheet = workbook["Stubs"]
    for row in range(5, properties.max_row + 1):
        for column in range(1, max(properties.max_column, 8) + 1):
            properties.cell(row, column).value = None
    for row in range(1, values.max_row + 1):
        for column in range(1, values.max_column + 1):
            values.cell(row, column).value = None
    for row in range(5, stubs_sheet.max_row + 1):
        for column in range(1, max(stubs_sheet.max_column, 4) + 1):
            stubs_sheet.cell(row, column).value = None

    for column_index, column in enumerate(columns, 2):
        name, channel = column[:2]
        token = column[2] if len(column) > 2 else ("i" if channel == "input" else "o")
        values.cell(1, column_index).value = name
        values.cell(2, column_index).value = token
    for index, row in enumerate(rows, 1):
        properties.cell(index + 4, 1).value = str(index)
        properties.cell(index + 4, 2).value = "0"
        properties.cell(index + 4, 5).value = (
            f"Test Case ID: {row['id']}\nDescription: {row['description']}"
        )
        values.cell(index + 2, 1).value = f"tc{index}.1"
        for column_index, column in enumerate(columns, 2):
            name, channel = column[:2]
            source = row["input"] if channel == "input" else row["output"]
            values.cell(index + 2, column_index).value = source[name]
    for index, stub in enumerate(stubs, 5):
        stubs_sheet.cell(index, 1).value = "0"
        stubs_sheet.cell(index, 2).value = "0"
        stubs_sheet.cell(index, 3).value = stub["name"]
        stubs_sheet.cell(index, 4).value = stub["body"]


def updateTestlistToExcel(func , templateFile , saveFileName , testList , testMethodlist , stubList , arg_name , arg_direction , arg_format,
                          project_name=None, module_name=None, export_date=None):
    wb = load_workbook(templateFile)
    if project_name is not None or module_name is not None or export_date is not None:
        if project_name is None or module_name is None:
            raise ValueError("project_name and module_name are required to write General metadata")
        writeGeneralSheet(wb.worksheets[0], project_name, module_name, func, export_date)
    columns = []
    typed_vars = set()
    for name, direction, fmt in zip(arg_name, arg_direction, arg_format):
        channel = "input" if direction in {"in", "inout"} else "output"
        base = name.split('.')[0]
        columns.append((name, channel, convertDirectionToTessyFormat(direction, name, fmt, base not in typed_vars)))
        typed_vars.add(base)
    rows = []
    for index, values in enumerate(testList, 1):
        description = f"测试{func}() 的正向测试"
        rows.append({
            "id": f"UT_TBD_{index:03d}",
            "description": description,
            "input": {name: str(value) for name, value, direction in zip(arg_name, values, arg_direction) if direction in {"in", "inout"}},
            "output": {name: str(value) for name, value, direction in zip(arg_name, values, arg_direction) if direction in {"out", "inout"}},
        })
    value_vars = {name.split('.')[0] for name in arg_name}
    stubs = []
    for name, ret_type, ret_name, _ in stubList:
        has_return = ret_type not in ("void", "static void")
        provides_value = ret_name in value_vars
        body = ""
        if has_return and provides_value:
            body = f"extern {ret_type} {ret_name};\rreturn {ret_name};\r"
        elif has_return:
            body = f"{ret_type} temp = {{0}};\rreturn temp;\r"
        stubs.append({"name": name, "body": body})
    write_testlist_cells(wb, rows, stubs, columns)
    wb.save( saveFileName ) ##newFileName )

def convertDirectionToTessyFormat(direction , name='' , fmt='', show_type=True):
    newDir = 'i' if direction == "in" else 'o'
    if name.startswith('tessy_') and show_type:   ### tessy_<name> variable shows its type once: i(SomeType); other members just i/o
        newDir += '(' + fmt + ')'
    return newDir
